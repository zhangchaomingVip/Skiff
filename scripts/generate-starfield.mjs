// Deterministic, transparent artwork: tiny stars stay still; only selected bright stars breathe.
// Run from the repository root with: node scripts/generate-starfield.mjs
import { mkdirSync, writeFileSync } from "node:fs";

let seed = 74129;
const random = () => ((seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0) / 4294967296);
const tones = ["#dce8ff", "#a4c7ff", "#ffffff", "#f7e5da"];
// A full field plus loose clusters gives the sky depth instead of an evenly spaced dusting.
const clusters = [[540, 250, 260, 180], [990, 570, 320, 230], [420, 840, 240, 150]];
const points = Array.from({ length: 5000 }, (_, index) => {
	let x = random() * 1440;
	let y = random() * 960;
	if (index >= 3600) {
		const [cx, cy, rx, ry] = clusters[index % clusters.length];
		const angle = random() * Math.PI * 2;
		const distance = Math.sqrt(random());
		x = (cx + Math.cos(angle) * distance * rx + 1440) % 1440;
		y = (cy + Math.sin(angle) * distance * ry + 960) % 960;
	}
	const radius = (.3 + random() ** 2.5 * .85).toFixed(2);
	const opacity = (.2 + random() * .62).toFixed(2);
	const color = tones[Math.floor(random() * tones.length)];
	return `<circle cx="${x.toFixed(2)}" cy="${y.toFixed(2)}" r="${radius}" fill="${color}" opacity="${opacity}"/>`;
});
// Medium stars bridge the fine points and the large breathing stars.
const medium = Array.from({ length: 200 }, () => {
	const x = (random() * 1440).toFixed(2);
	const y = (random() * 960).toFixed(2);
	const radius = (.8 + random() * .65).toFixed(2);
	const tone = random() > .25 ? "blue" : "white";
	const opacity = (.6 + random() * .35).toFixed(2);
	return `<g transform="translate(${x} ${y})" opacity="${opacity}"><circle r="${(Number(radius) * 3.5).toFixed(2)}" fill="url(#${tone})"/><circle r="${radius}" fill="${tone === "blue" ? "#dceaff" : "#fff2e8"}"/></g>`;
});
const bright = [
	[220, 310, 1, "blue"], [470, 215, .8, "blue"], [670, 140, 1, "white"],
	[1270, 360, .7, "white"], [1175, 440, .85, "white"], [1070, 670, 1.1, "blue"],
	[1180, 735, .8, "white"], [360, 770, .45, "blue"], [790, 540, .4, "white"],
	[1350, 840, .45, "blue"], [900, 45, .35, "white"],
].map(([x, y, size, tone], index) => `<g transform="translate(${x} ${y}) scale(${size})">
	<g${index < 7 ? ` class="beacon" style="animation-duration:${5 + index % 4}s;animation-delay:-${(index * 1.37).toFixed(2)}s"` : ""}>
		<circle r="18" fill="url(#${tone})"/>
		<path d="M0-15 1.2-2 15 0 1.2 2 0 15-1.2 2-15 0-1.2-2Z" fill="url(#${tone})"/>
		<path d="M0-9 .65-.65 9 0 .65.65 0 9-.65.65-9 0-.65-.65Z" fill="#e8f1ff" opacity=".8"/>
		<circle r="1.3" fill="#ffffff"/>
	</g>
</g>`);
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="1440" height="960" viewBox="0 0 1440 960">
<!-- Generated by scripts/generate-starfield.mjs. No background, text, scripts or external resources. -->
<style>
.beacon { animation: breathe 6s ease-in-out infinite; transform-origin: 0 0; }
@keyframes breathe { 0%, 100% { opacity: .3; transform: scale(.78); } 50% { opacity: .95; transform: scale(1.12); } }
@media (prefers-reduced-motion: reduce) { .beacon { animation: none; opacity: .65; } }
</style>
<defs>
	<radialGradient id="blue"><stop stop-color="#ffffff" stop-opacity=".95"/><stop offset=".12" stop-color="#bbd7ff" stop-opacity=".85"/><stop offset=".3" stop-color="#649cff" stop-opacity=".4"/><stop offset="1" stop-color="#397bff" stop-opacity="0"/></radialGradient>
	<radialGradient id="white"><stop stop-color="#ffffff" stop-opacity=".95"/><stop offset=".15" stop-color="#fff0e5" stop-opacity=".75"/><stop offset=".35" stop-color="#cbd5ff" stop-opacity=".25"/><stop offset="1" stop-color="#adc6ff" stop-opacity="0"/></radialGradient>
</defs>
${points.join("\n")}
${medium.join("\n")}
${bright.join("\n")}
</svg>
`;
mkdirSync(new URL("../public/themes/", import.meta.url), { recursive: true });
writeFileSync(new URL("../public/themes/stars.svg", import.meta.url), svg);
// SVG image documents do not reliably receive live reduced-motion changes in WebView2.
// A separate still image lets the host stylesheet switch them immediately.
writeFileSync(new URL("../public/themes/stars-static.svg", import.meta.url), svg.replace(/<style>[\s\S]*?<\/style>/, "<style>.beacon { opacity: .65; }</style>"));
