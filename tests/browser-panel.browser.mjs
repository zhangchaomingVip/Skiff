import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdir } from "node:fs/promises";
import { join } from "node:path";

const require = createRequire(import.meta.url);
const { chromium } = require(join(process.cwd(), ".playwright-cli/node_modules/playwright-core"));
const output = join(process.cwd(), "dist/browser-panel"); await mkdir(output, { recursive: true });
const origin = process.argv[2] ?? "http://localhost:1421";
const browser = await chromium.launch({ channel: "msedge", headless: true });
try {
	for (const theme of ["light", "dark"]) {
		const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
		const errors = []; page.on("pageerror", (error) => errors.push(String(error)));
		await page.goto(`${origin}/tests/preview.html?fixture=browser&theme=${theme}`);
		await page.waitForFunction(() => document.querySelector(".sidebar")?.dataset.connected === "true");
		const panel = page.getByRole("region", { name: "浏览器画面", exact: true });
		const live = () => page.locator('.browser-screen[data-phase="live"]').waitFor();
		const trigger = page.getByRole("button", { name: "浏览器", exact: true });
		const set = (chatId, patch = {}) => page.evaluate(({ chatId, patch }) => window.skiffPreview.browser.set(chatId, patch), { chatId, patch });
		const noSockets = () => page.waitForFunction(() => window.skiffPreview.browser.sockets.size === 0);
		await page.fill(".composer-input", "保留浏览草稿 A");
		await page.getByRole("button", { name: "航行台", exact: true }).click();
		await set("browser-a", { control: "starting", url: null });
		await panel.waitFor(); await page.getByText("正在启动浏览器…", { exact: true }).waitFor();
		assert.equal(await page.locator(".voyage-rail").count(), 0);
		const longUrl = `https://example.test/中文路径/${"long-address/".repeat(70)}`;
		await set("browser-a", { control: "ai", url: longUrl }); await live();
		assert.equal(await panel.getAttribute("data-chat-id"), "browser-a");
		await page.waitForFunction(() => Number(document.querySelector(".browser-screen canvas")?.dataset.frame) >= 3);
		assert.equal(await page.evaluate(() => window.skiffPreview.browser.sent.some((message) => message.type.startsWith("input_"))), false, "Watching sends no input");
		await page.screenshot({ animations: "disabled", path: join(output, `${theme}.png`) });
		const separator = page.getByRole("separator", { name: "调整浏览器面板宽度" });
		const before = Number(await separator.getAttribute("aria-valuenow"));
		await separator.focus(); await page.keyboard.press("ArrowLeft");
		assert.equal(Number(await separator.getAttribute("aria-valuenow")), before + 12);
		await page.getByRole("button", { name: "收起浏览器", exact: true }).click(); await noSockets();
		await page.waitForFunction(() => document.activeElement?.classList.contains("browser-trigger"));
		await set("browser-a", { url: "https://example.test/next-operation" }); await page.waitForTimeout(1200);
		assert.equal(await panel.count(), 0, "Later operations do not reopen manually collapsed panel");
		assert.equal(await page.inputValue(".composer-input"), "保留浏览草稿 A");
		await trigger.click(); await live();
		await page.evaluate(() => window.skiffPreview.browser.disconnect("browser-a"));
		await page.getByText("画面连接已断开", { exact: true }).waitFor();
		assert.equal(await page.locator(".browser-screen canvas").getAttribute("width"), "0");
		await page.getByRole("button", { name: "重新连接画面", exact: true }).click(); await live();
		await page.evaluate(() => { Object.defineProperty(document, "hidden", { configurable: true, value: true }); document.dispatchEvent(new Event("visibilitychange")); });
		await noSockets(); await page.getByText("画面已暂停", { exact: true }).waitFor();
		await page.evaluate(() => { Object.defineProperty(document, "hidden", { configurable: true, value: false }); document.dispatchEvent(new Event("visibilitychange")); }); await live();
		await page.getByRole("button", { name: "航行台", exact: true }).click(); await noSockets();
		assert.equal(await page.getByRole("button", { name: "航行台", exact: true }).getAttribute("aria-pressed"), "true");
		await trigger.click(); await live();
		await set("browser-b", { url: "https://other.test/b" });
		await page.locator('.sidebar .chat-link').filter({ hasText: "浏览任务 B" }).first().click();
		await page.waitForFunction(() => document.querySelector(".browser-panel")?.dataset.chatId === "browser-b"); await live();
		assert.equal(await page.evaluate(() => [...window.skiffPreview.browser.sockets].every((socket) => socket.chatId === "browser-b")), true);
		await page.fill(".composer-input", "保留浏览草稿 B");
		await page.evaluate(() => { window.releaseOldBrowser = window.skiffPreview.browser.deferFind("browser-b"); });
		await page.waitForTimeout(1100);
		await page.locator('.sidebar .chat-link').filter({ hasText: "浏览任务 A" }).first().click();
		await page.waitForFunction(() => document.querySelector(".browser-panel")?.dataset.chatId === "browser-a"); await live();
		await page.evaluate(() => window.releaseOldBrowser());
		assert.equal(await panel.getAttribute("data-chat-id"), "browser-a", "Late old-chat query cannot replace active owner");
		assert.equal(await page.inputValue(".composer-input"), "保留浏览草稿 A");
		await page.setViewportSize({ width: 600, height: 400 });
		await page.getByRole("button", { name: "返回聊天", exact: true }).waitFor();
		assert.equal(await page.locator(".composer-input").isVisible(), false);
		assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
		await page.screenshot({ animations: "disabled", path: join(output, `${theme}-narrow.png`) });
		await page.getByRole("button", { name: "返回聊天", exact: true }).click(); await noSockets();
		assert.equal(await page.inputValue(".composer-input"), "保留浏览草稿 A");
		await trigger.click(); await live(); await page.keyboard.press("Escape"); await noSockets();
		await page.setViewportSize({ width: 1440, height: 900 });
		await trigger.click(); await live();
		await set("browser-a", { control: "closed", controlVersion: 2 });
		await page.getByText("浏览器已关闭", { exact: true }).waitFor(); await noSockets();
		await set("browser-a", { generation: "replacement", control: "ai", controlVersion: 1 }); await live();
		await page.waitForFunction(() => document.querySelector(".browser-panel")?.dataset.generation === "replacement");
		assert.equal(await page.evaluate(() => window.skiffPreview.browser.calls.some((call) => ["browser_start", "browser_control", "browser_close"].includes(call.command))), false, "Panel never starts, stops or closes browser while viewing");
		await set("browser-a", { control: "faulted", error: "无法确认在途操作已结束", controlVersion: 2 });
		await page.getByText("浏览器故障", { exact: true }).first().waitFor(); await noSockets();
		await page.getByRole("button", { name: "关闭并重新准备", exact: true }).click();
		await page.getByText("浏览器已关闭", { exact: true }).waitFor();
		assert.equal(await page.evaluate(() => window.skiffPreview.browser.calls.filter((call) => call.command === "browser_close").length), 1);
		assert.deepEqual(errors, []);
		await page.close();
	}
	const page = await browser.newPage({ viewport: { width: 1100, height: 750 } });
	await page.goto(`${origin}/tests/preview.html?fixture=browser&theme=light`);
	await page.waitForFunction(() => document.querySelector(".sidebar")?.dataset.connected === "true");
	await page.evaluate(() => { window.skiffPreview.browser.setReady(false); });
	await page.getByRole("button", { name: "浏览器", exact: true }).click();
	await page.getByText("浏览器尚未就绪", { exact: true }).waitFor();
	await page.getByRole("button", { name: "浏览器设置", exact: true }).click();
	await page.getByText("npm install -g agent-browser@0.41.2", { exact: true }).waitFor();
	await page.screenshot({ animations: "disabled", path: join(output, "missing-dependency.png") });
	const cli = page.getByRole("textbox", { name: "自定义 agent-browser 路径", exact: true });
	assert.equal(await cli.inputValue(), "", "Automatic discovery is not a manual override");
	await cli.fill("C:/test/agent-browser.exe");
	await page.getByRole("button", { name: "保存路径", exact: true }).click();
	await page.getByRole("button", { name: "保存路径", exact: true }).waitFor({ state: "visible" });
	await page.waitForFunction(() => window.skiffPreview.browser.calls.some((call) => call.command === "browser_configure" && call.args.settings.cliPath === "C:/test/agent-browser.exe"));
	await page.getByRole("button", { name: "重新检测依赖", exact: true }).click();
	assert.equal(await cli.inputValue(), "C:/test/agent-browser.exe");
	await cli.fill(""); await page.getByRole("button", { name: "保存路径", exact: true }).click();
	await page.waitForFunction(() => window.skiffPreview.browser.calls.some((call) => call.command === "browser_configure" && call.args.settings.cliPath === null));
	await page.getByRole("button", { name: "关闭设置", exact: true }).click();
	await page.evaluate(() => window.skiffPreview.browser.setReady(true));
	await page.getByRole("button", { name: "重新检测", exact: true }).click();
	await page.getByText("AI 浏览器尚未启用", { exact: true }).waitFor();
	await page.close();
	console.log("PASS browser panel: themes, live JPEG, bounded ownership, manual collapse, reconnect, drafts, keyboard resize, narrow back, closed/replacement and dependencies");
} finally { await browser.close(); }
