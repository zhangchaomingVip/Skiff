const tool = (name) => page.getByRole("navigation", { name: "工作区工具" }).getByRole("button", { name, exact: true });
const tab = (name) => page.getByRole("tab", { name, exact: true });
const assertHeaderLayout = async (actions) => {
	const header = page.locator(".workbench-header");
	for (const name of actions) await header.getByRole("button", { name, exact: true }).waitFor();
	assert.deepEqual(await header.locator(".workbench-header-actions button").evaluateAll((elements) => elements.map((element) => [element.getAttribute("aria-label"), element.dataset.variant, element.dataset.size])), actions.map((name) => [name, "ghost", "compact"]));
	const bounds = await page.locator(".workbench-panel").evaluate((panel) => {
		const rect = (selector) => { const box = panel.querySelector(selector).getBoundingClientRect(); return { top: box.top, bottom: box.bottom, height: box.height }; };
		return { header: rect(".workbench-header"), tabs: rect(".workbench-tabs"), content: rect(".workbench-tool-slot:not([hidden]) > .workbench-section") };
	});
	assert.equal(bounds.header.height, 44);
	assert.equal(bounds.tabs.height, 40);
	assert.equal(bounds.header.bottom, bounds.tabs.top);
	assert.equal(bounds.tabs.bottom, bounds.content.top, "Content must directly follow the tabs without another toolbar row");
	assert.equal(await page.locator(".workbench-tab-actions, .git-branches .workbench-toolbar").count(), 0);
};

