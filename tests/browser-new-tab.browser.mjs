import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdir } from "node:fs/promises";
import { join } from "node:path";

const require = createRequire(import.meta.url);
const { chromium } = require(join(process.cwd(), ".playwright-cli/node_modules/playwright-core"));
const origin = process.argv[2] ?? "http://localhost:1421";
const output = join(process.cwd(), "dist/browser-new-tab");
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: "msedge", headless: true });
try {
	for (const theme of ["light", "dark"]) {
		const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
		const errors = []; page.on("pageerror", (error) => errors.push(String(error)));
		await page.goto(`${origin}/tests/preview.html?fixture=browser&persist=1&theme=${theme}`);
		await page.waitForFunction(() => document.querySelector(".sidebar")?.dataset.connected === "true");
		await page.evaluate(() => { window.skiffPreview.browser.setEnabled(true); window.skiffPreview.browser.set("browser-a", { control: "human" }); });
		await page.locator('.browser-screen[data-phase="live"]').waitFor();
		assert.equal(await page.locator(".browser-handoff, .browser-notice").count(), 0);
		await page.getByRole("button", { name: "新建标签页", exact: true }).click();
		await page.locator(".browser-new-page").waitFor();
		await page.waitForFunction(() => document.activeElement?.classList.contains("browser-address-input"));
		assert.equal(await page.locator(".browser-toolbar, .browser-screen").count(), 0, "Blank page does not require a stream");
		await page.evaluate(() => window.skiffPreview.browser.failTab("模拟关闭失败"));
		await page.locator(".browser-tab.is-active .browser-tab-close").click();
		await page.getByRole("alert").filter({ hasText: "模拟关闭失败" }).waitFor();
		assert.equal(await page.locator(".browser-tab").count(), 2);
		await page.locator(".browser-tab.is-active .browser-tab-close").click();
		await page.waitForFunction(() => window.skiffPreview.browser.entries.get("browser-a").tabs.length === 1);
		await page.getByRole("button", { name: "新建标签页", exact: true }).click();
		await page.locator(".browser-new-page").waitFor();
		await page.getByRole("combobox", { name: "地址栏" }).focus();
		await page.keyboard.press("Escape");
		assert.equal(await page.locator(".browser-panel").count(), 1);
		await page.screenshot({ path: join(output, `${theme}-new-tab.png`) });
		await page.getByRole("combobox", { name: "地址栏" }).focus();
		await page.getByRole("combobox", { name: "地址栏" }).fill("示例");
		await page.getByRole("listbox", { name: "浏览历史建议" }).waitFor();
		await page.screenshot({ path: join(output, `${theme}-suggestions.png`) });
		await page.getByRole("button", { name: /删除历史记录/ }).first().click();
		await page.waitForTimeout(1200);
		assert.equal(await page.getByRole("option").count(), 0, "Polling cannot restore a deleted suggestion");
		const address = page.getByRole("combobox", { name: "地址栏" });
		await address.fill("gemini");
		await address.evaluate((input) => input.dispatchEvent(new KeyboardEvent("keydown", { key: "Enter", isComposing: true, bubbles: true })));
		assert.equal(await page.locator(".browser-new-page").count(), 1);
		await address.press("Enter");
		await page.waitForFunction(() => window.skiffPreview.browser.entries.get("browser-a").url === "https://www.google.com/search?q=gemini");
		await page.locator('.browser-screen[data-phase="live"]').waitFor();
		await page.screenshot({ path: join(output, `${theme}-page.png`) });
		await page.evaluate(() => window.skiffPreview.browser.disconnect("browser-a"));
		await page.getByText("画面连接已断开", { exact: true }).waitFor();
		await page.locator(".browser-tab.is-active .browser-tab-close").click();
		await page.waitForFunction(() => window.skiffPreview.browser.entries.get("browser-a").tabs.length === 1);
		for (let i = 0; i < 3; i++) {
			await page.getByRole("button", { name: "新建标签页", exact: true }).click();
			await page.locator(".browser-new-page").waitFor();
			await page.locator(".browser-tab.is-active .browser-tab-close").click();
			await page.waitForFunction(() => window.skiffPreview.browser.entries.get("browser-a").tabs.length === 1);
		}
		await page.evaluate(() => window.skiffPreview.browser.failClose("模拟实例关闭失败"));
		await page.locator(".browser-tab-close").click();
		await page.getByRole("alert").filter({ hasText: "模拟实例关闭失败" }).waitFor();
		assert.equal(await page.locator(".browser-panel").count(), 1);
		await page.locator(".browser-tab-close").click();
		await page.locator(".browser-panel").waitFor({ state: "detached" });
		assert.equal(await page.locator(".composer-input").isVisible(), true);
		await page.getByRole("button", { name: "浏览器", exact: true }).click();
		await page.getByRole("button", { name: "打开浏览器", exact: true }).click();
		await page.locator(".browser-new-page").waitFor();
		await address.fill("google.com");
		await page.getByRole("option").first().waitFor();
		await address.press("ArrowDown"); await address.press("Enter");
		await page.locator(".browser-address-display").waitFor();
		await page.setViewportSize({ width: 600, height: 500 });
		await page.getByRole("button", { name: "新建标签页", exact: true }).click();
		await page.locator(".browser-new-page").waitFor();
		assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
		await page.screenshot({ path: join(output, `${theme}-narrow.png`) });
		await page.setViewportSize({ width: 1440, height: 900 });
		await page.getByRole("navigation", { name: "工作区工具" }).getByRole("button", { name: "对话", expanded: false, exact: true }).click();
		await page.evaluate(() => { window.skiffPreview.browser.set("browser-b", { control: "human" }); window.releaseTab = window.skiffPreview.browser.deferTab(); });
		await page.getByRole("button", { name: "新建标签页", exact: true }).click();
		await page.locator(".sidebar .chat-link").filter({ hasText: "浏览任务 B" }).first().click();
		await page.waitForFunction(() => document.querySelector(".browser-panel")?.dataset.chatId === "browser-b");
		await page.evaluate(() => window.releaseTab());
		await page.waitForTimeout(250);
		assert.equal(await page.locator(".browser-panel").getAttribute("data-chat-id"), "browser-b");
		assert.equal(await page.locator(".browser-tab").count(), 1, "Old-chat operation cannot update the selected chat");
		await page.reload();
		assert.ok(await page.evaluate(() => JSON.parse(localStorage.getItem("skiff.browser.history.v1")).some((item) => item.url.includes("google.com"))));
		assert.deepEqual(errors, []);
		await page.close();
	}
	console.log("PASS new tab: no stream dependency, immediate close, last close, suggestions, Google, IME, history persistence and both themes");
} finally { await browser.close(); }
