import { workbenchTool } from "./workspace-navigation.mjs";
import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { chromium } from "../.playwright-cli/node_modules/playwright-core/index.mjs";
import { testImage } from "./imageFixture.mjs";

const origin = process.argv[2] ?? "http://localhost:1421";
await mkdir("dist/video-generation", { recursive: true });
const browser = await chromium.launch({ headless: true, channel: "msedge" });
const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
page.setDefaultTimeout(15000);
const errors = []; page.on("pageerror", (error) => errors.push(String(error)));
const tool = (name) => workbenchTool(page, name);
const settings = () => page.getByRole("dialog", { name: "设置", exact: true });
const prompt = () => page.getByRole("textbox", { name: "提示词 Prompt", exact: true });
const generate = () => page.locator(".generation-controls").getByRole("button", { name: "生成视频", exact: true });
const setMode = (mode) => page.evaluate((mode) => window.skiffPreview.videos.setMode(mode), mode);
try {
	for (const theme of ["light", "dark"]) {
		await page.setViewportSize({ width: 1440, height: 960 });
		await page.goto(`${origin}/tests/preview.html?fixture=sidebar&theme=${theme}`);
		await page.locator(".composer-input").fill("视频任务不会丢失聊天草稿");
		await tool("生成视频").click();
		assert.equal(await generate().isDisabled(), true);
		assert.equal(await page.getByRole("slider").count(), 0);
		await page.getByRole("button", { name: "配置视频服务", exact: true }).click();
		await settings().getByRole("button", { name: "添加视频服务", exact: true }).click();
		await settings().getByRole("textbox", { name: "服务名称", exact: true }).fill("Muse 测试服务");
		await settings().getByRole("textbox", { name: "API Key", exact: true }).fill("dummy-video-key-5678");
		assert.equal(await settings().getByRole("checkbox", { name: "启用单图参考（实验）", exact: true }).isChecked(), false);
		await settings().getByRole("checkbox", { name: "启用单图参考（实验）", exact: true }).check();
		await settings().getByRole("button", { name: "保存视频服务", exact: true }).click();
		await settings().getByRole("button", { name: "编辑视频服务 Muse 测试服务", exact: true }).click();
		assert.equal(await settings().getByRole("textbox", { name: "API Key", exact: true }).inputValue(), "");
		assert.equal(await page.evaluate(() => window.skiffPreview.videos.calls.length), 0);
		await settings().getByRole("button", { name: "取消编辑", exact: true }).click();
		await settings().getByRole("button", { name: "关闭设置", exact: true }).click();
		await prompt().fill("蓝色纸船，海面波光，缓慢推进");
		await page.locator('input[aria-label="上传首帧参考图"]').setInputFiles({ name: "boat.png", mimeType: "image/png", buffer: testImage() });
		await setMode("pending"); await generate().click();
		await page.getByRole("status").filter({ hasText: "正在生成视频…" }).waitFor();
		assert.equal(await generate().isDisabled(), true);
		await tool("对话").click(); assert.equal(await page.locator(".composer-input").inputValue(), "视频任务不会丢失聊天草稿"); await tool("生成视频").click();
		assert.equal(await prompt().inputValue(), "蓝色纸船，海面波光，缓慢推进");
		await page.screenshot({ path: `dist/video-generation/${theme}-pending.png` });
		await page.getByRole("button", { name: "暂停查询", exact: true }).click();
		await page.getByRole("status").filter({ hasText: "已暂停查询" }).waitFor(); assert.equal(await generate().isDisabled(), true);
		await setMode("success"); await page.getByRole("button", { name: "继续查询", exact: true }).click();
		await page.getByText("生成作品", { exact: true }).waitFor();
		const calls = await page.evaluate(() => window.skiffPreview.videos.calls);
		assert.equal(calls.length, 1); assert.equal(calls[0].hasReference, true); assert.equal(calls[0].referencePrefix, "data:image/jpeg;base64,"); assert.equal("apiKey" in calls[0], false);
		await page.locator(".generation-card-preview").click();
		const preview = page.getByRole("dialog", { name: "视频预览", exact: true });
		await page.waitForFunction(() => document.querySelector("dialog video")?.readyState >= 2);
		await page.waitForFunction(() => !document.querySelector("dialog video")?.paused);
		assert.match(await preview.innerText(), /72 × 128/); assert.match(await preview.innerText(), /5.00 秒/);
		await preview.locator("video").evaluate((video) => { video.currentTime = 2; video.muted = false; });
		assert.equal(await preview.locator("video").evaluate((video) => video.controls && !video.muted && video.currentTime >= 2), true);
		await page.screenshot({ path: `dist/video-generation/${theme}-preview.png` });
		await preview.getByRole("button", { name: "另存为", exact: true }).click();
		await preview.getByRole("button", { name: "打开所在文件夹", exact: true }).click();
		await page.keyboard.press("Escape");
		await page.getByRole("button", { name: "移除首帧参考图", exact: true }).click();
		await setMode("download-failure"); await prompt().fill("下载失败后只重试下载"); await generate().click();
		await page.getByRole("status").filter({ hasText: "视频下载失败" }).waitFor();
		await setMode("success"); await page.getByRole("button", { name: "重新下载", exact: true }).click();
		await page.waitForFunction(() => document.querySelectorAll(".generation-card").length === 2);
		assert.equal(await page.evaluate(() => window.skiffPreview.videos.calls.filter((call) => !call.command).length), 2);
		await setMode("unknown"); await prompt().fill("提交结果未知"); await generate().click();
		await page.getByRole("status").filter({ hasText: "提交结果待核对" }).waitFor();
		assert.equal(await generate().isDisabled(), true);
		await page.getByRole("button", { name: "核对后结束跟踪", exact: true }).click();
		await page.getByRole("dialog", { name: "结束本地任务跟踪？", exact: true }).getByRole("button", { name: "已核对，结束跟踪", exact: true }).click();
		await page.getByRole("status").filter({ hasText: "已结束本地跟踪" }).waitFor();
		await page.evaluate(() => { const url = new URL(location.href); url.searchParams.set("persist", "1"); history.replaceState(null, "", url); });
		await page.reload(); await page.waitForFunction(() => document.querySelectorAll(".generation-card").length === 2);
		await page.screenshot({ path: `dist/video-generation/${theme}-gallery.png` });
		await page.setViewportSize({ width: 600, height: 400 });
		assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
		await page.screenshot({ path: `dist/video-generation/${theme}-narrow.png` });
		console.log(`PASS ${theme}: video configuration, reference snapshot, pause/resume, playback/seek/audio, download retry, unknown submission, persistence and narrow layout`);
	}
	assert.deepEqual(errors, []);
} finally { await browser.close(); }
