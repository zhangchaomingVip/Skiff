import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import assert from "node:assert/strict";

// Called inside app.cdp.mjs's existing storage snapshot/restore boundary.
export async function verifyGitTree(page, temporaryRoot, artifacts) {
	const root = join(temporaryRoot, "history-repo");
	await mkdir(root);
	const execute = promisify(execFile);
	const git = async (...args) => (await execute("git", args, { cwd: root, windowsHide: true })).stdout.trim();
	await git("init", "-q", "-b", "main");
	await git("config", "user.email", "cdp@example.invalid");
	await git("config", "user.name", "CDP History");
	await writeFile(join(root, "history.txt"), "initial historical content\n");
	await git("add", "."); await git("commit", "-qm", "Initial history fixture");
	await git("checkout", "-qb", "feature/tree");
	await writeFile(join(root, "feature.txt"), "feature history\n");
	await git("add", "."); await git("commit", "-qm", "Feature history fixture");
	await git("checkout", "-q", "main");
	await writeFile(join(root, "history.txt"), "updated historical content\n");
	await git("add", "."); await git("commit", "-qm", "Update history fixture");
	await git("merge", "--no-ff", "feature/tree", "-m", "Merge history fixture");
	await git("tag", "-a", "v1", "-m", "history release");
	await git("update-ref", "refs/remotes/origin/main", "HEAD");
	await writeFile(join(root, "history.txt"), "uncommitted content must stay\n");
	const head = await git("rev-parse", "HEAD");
	const index = await readFile(join(root, ".git", "index"));
	await page.evaluate((root) => {
		localStorage.setItem("skiff.workspace.v1", JSON.stringify({ version: 1, projects: [{ id: "history-project", name: "History fixture", path: root }], chats: [{ id: "history-chat", projectId: "history-project", title: "History", updatedAt: Date.now(), hasMessages: false }], activeId: "history-chat" }));
		localStorage.setItem("skiff.workbench.v1", JSON.stringify({ version: 1, tool: "chats" }));
		localStorage.setItem("skiff.sidebar.open", "true");
	}, root);
	await page.reload({ waitUntil: "domcontentloaded" });
	await page.getByRole("navigation", { name: "工作区工具" }).getByRole("button", { name: "Git Tree", exact: true }).click();
	await page.getByRole("heading", { name: "Merge history fixture", exact: true }).waitFor();
	assert.equal(await page.getByRole("option").count(), 4);
	await page.getByRole("button", { name: "feature.txt A", exact: true }).click();
	await page.locator(".history-diff .diff-preview").waitFor();
	assert.match(await page.locator(".history-diff").textContent(), /\+feature history/);
	await page.getByRole("button", { name: "feature/tree", exact: true }).click();
	await page.waitForFunction(() => document.querySelectorAll(".commit-log-row").length === 2);
	await page.getByRole("option").filter({ hasText: "Initial history fixture" }).click();
	await page.getByRole("button", { name: "history.txt A", exact: true }).click();
	await page.locator(".history-diff .diff-preview").waitFor();
	assert.match(await page.locator(".history-diff").textContent(), /\+initial historical content/);
	assert.doesNotMatch(await page.locator(".history-diff").textContent(), /uncommitted content/);
	await page.getByRole("button", { name: "所有分支", exact: true }).click();
	await page.waitForFunction(() => document.querySelectorAll(".commit-log-row").length === 4);
	await page.getByRole("heading", { name: "Merge history fixture", exact: true }).waitFor();
	await page.screenshot({ path: join(artifacts, "git-tree-cdp.png") });
	assert.equal(await git("rev-parse", "HEAD"), head);
	assert.deepEqual(await readFile(join(root, ".git", "index")), index);
	assert.equal(await readFile(join(root, "history.txt"), "utf8"), "uncommitted content must stay\n");
	console.log("Git Tree 全链路通过：真实分支、合并图、提交详情与历史 Diff；HEAD、index 和工作区未变。");

	// Exercise Update Project with a local-only remote, never the developer's repo.
	const update = () => page.locator(".git-log-toolbar").getByRole("button", { name: "Update Project", exact: true });
	await update().click();
	await page.getByRole("alert").filter({ hasText: "未提交" }).waitFor();
	assert.equal(await readFile(join(root, "history.txt"), "utf8"), "uncommitted content must stay\n");
	await git("restore", "history.txt");
	const remote = join(temporaryRoot, "history-remote.git");
	const writer = join(temporaryRoot, "history-writer");
	await execute("git", ["clone", "--bare", root, remote], { windowsHide: true });
	await git("remote", "add", "origin", remote);
	await git("fetch", "origin");
	await git("branch", "--set-upstream-to", "origin/main");
	await execute("git", ["clone", remote, writer], { windowsHide: true });
	const writeGit = async (...args) => (await execute("git", args, { cwd: writer, windowsHide: true })).stdout.trim();
	await writeGit("config", "user.email", "cdp@example.invalid");
	await writeGit("config", "user.name", "CDP Remote");
	await writeFile(join(writer, "history.txt"), "downloaded by Update Project\n");
	await writeGit("add", "."); await writeGit("commit", "-qm", "Remote fast-forward update");
	await writeGit("push", "origin", "main");
	const remoteHead = await writeGit("rev-parse", "HEAD");
	await update().click();
	await page.getByRole("status").filter({ hasText: "快进更新到" }).waitFor();
	await page.getByRole("heading", { name: "Remote fast-forward update", exact: true }).waitFor();
	assert.equal(await git("rev-parse", "HEAD"), remoteHead);
	assert.equal((await readFile(join(root, "history.txt"), "utf8")).trim(), "downloaded by Update Project");
	await page.screenshot({ path: join(artifacts, "git-update-cdp.png") });
	await writeFile(join(root, "local-only.txt"), "preserve local commit\n");
	await git("add", "."); await git("commit", "-qm", "Local diverging commit");
	const localHead = await git("rev-parse", "HEAD");
	await writeFile(join(writer, "remote-only.txt"), "different remote commit\n");
	await writeGit("add", "."); await writeGit("commit", "-qm", "Remote diverging commit"); await writeGit("push", "origin", "main");
	await page.locator(".git-branches").getByRole("button", { name: "Update Project", exact: true }).click();
	await page.getByRole("status").filter({ hasText: "已分叉" }).waitFor();
	assert.equal(await git("rev-parse", "HEAD"), localHead);
	assert.equal(await git("status", "--porcelain"), "");
	console.log("Update Project 全链路通过：未提交改动拦截、远程快进、分叉保留本地提交；两个入口使用相同策略。");
}
