import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { chromium } from "../.playwright-cli/node_modules/playwright-core/index.mjs";

const origin = process.argv[2] ?? "http://localhost:1421";
await mkdir("dist/image-generation", { recursive: true });
const browser = await chromium.launch({ headless: true, channel: "msedge" });
const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
page.setDefaultTimeout(10000);
const errors = [];
page.on("pageerror", (error) => errors.push(String(error)));
const tool = (name) => page.getByRole("navigation", { name: "工作区工具" }).getByRole("button", { name, exact: true });
const generate = () => page.getByRole("button", { name: "生成图片", exact: true });
const prompt = () => page.getByRole("textbox", { name: "提示词 Prompt" });
const setting = () => page.getByRole("dialog", { name: "设置", exact: true });
await page.context().grantPermissions(["clipboard-read", "clipboard-write"], { origin });

try {
	for (const theme of ["light", "dark"]) {
		await page.goto(`${origin}/tests/preview.html?fixture=sidebar&theme=${theme}&color=yellow`);
		await page.waitForFunction(() => document.querySelector(".sidebar")?.dataset.connected === "true");
		await tool("生图").click();
		assert.equal(await generate().isDisabled(), true);
		await page.getByRole("button", { name: "配置生成服务", exact: true }).click();
		await setting().getByRole("button", { name: "添加生成服务" }).click();
		await setting().getByRole("textbox", { name: "服务名称", exact: true }).fill("本地图片验证");
		await setting().getByRole("textbox", { name: "API Key", exact: true }).fill("dummy-generation-secret-1234");
		await setting().getByRole("textbox", { name: "模型 ID 1", exact: true }).fill("test-image");
		await page.screenshot({ path: `dist/image-generation/${theme}-settings.png`, animations: "disabled" });
		await setting().getByRole("button", { name: "保存生成服务" }).click();
		await setting().getByRole("button", { name: "编辑生成服务 本地图片验证" }).waitFor();
		assert.equal(await page.evaluate(() => window.skiffPreview.generation.calls.length), 0, "Saving settings never generates an image");
		await setting().getByRole("button", { name: "编辑生成服务 本地图片验证" }).click();
		assert.equal(await setting().getByRole("textbox", { name: "API Key", exact: true }).inputValue(), "");
		await setting().getByRole("textbox", { name: "服务名称", exact: true }).fill("图片验证");
		await setting().getByRole("button", { name: "外观", exact: true }).click();
		await page.getByRole("button", { name: "继续编辑", exact: true }).click();
		await setting().getByRole("button", { name: "保存生成服务" }).click();
		await setting().getByRole("button", { name: "编辑生成服务 图片验证" }).waitFor();
		assert.match(await setting().innerText(), /1234/);
		assert.equal(await page.evaluate(() => JSON.stringify(localStorage).includes("dummy-generation-secret")), false);
		await setting().getByRole("button", { name: "关闭设置" }).click();
		await prompt().fill("可清空的草稿");
		await page.getByRole("button", { name: "清空提示词", exact: true }).click();
		assert.equal(await prompt().inputValue(), "");
		assert.equal(await prompt().evaluate((input) => input === document.activeElement), true);
		await prompt().fill("午后窗边的一束花，温暖的胶片质感");
		await page.getByRole("group", { name: "画面比例", exact: true }).getByRole("button", { name: /16:9/ }).click();
		await page.evaluate(() => window.skiffPreview.generation.setMode("pending"));
		await prompt().press("Control+Enter");
		await page.getByText("正在生成图片…", { exact: true }).waitFor();
		assert.equal(await page.locator(".generation-gallery-grid > :first-child").getAttribute("aria-busy"), "true");
		assert.equal(await page.locator(".generation-pending-glow").count(), 1);
		await prompt().press("Control+Enter");
		assert.equal(await page.evaluate(() => window.skiffPreview.generation.calls.length), 1, "Shortcut never duplicates a pending submission");
		assert.equal(await generate().isDisabled(), true);
		const call = await page.evaluate(() => window.skiffPreview.generation.calls[0]);
		assert.equal(call.modelId, "test-image"); assert.equal(call.size, "1536x864");
		assert.equal("apiKey" in call, false);
		await tool("对话").click(); await tool("生图").click();
		await page.getByText("正在生成图片…", { exact: true }).waitFor();
		await page.screenshot({ path: `dist/image-generation/${theme}-generating.png`, animations: "disabled" });
		await page.getByRole("button", { name: "停止等待", exact: true }).click();
		await page.getByRole("group", { name: "画廊视图", exact: true }).getByRole("button", { name: /^失败记录/ }).click();
		await page.getByText("已停止等待", { exact: true }).waitFor();
		await page.evaluate(() => window.skiffPreview.generation.setMode("success"));
		await prompt().press("Meta+Enter");
		await page.getByText("生成作品", { exact: true }).waitFor();
		await page.waitForFunction(() => document.querySelector(".generation-card img")?.naturalWidth > 0);
		const more = page.locator(".generation-card").getByRole("button", { name: /^更多作品操作/ });
		await more.focus(); await more.press("Enter");
		assert.equal(await page.getByRole("menuitem", { name: "使用提示词", exact: true }).evaluate((button) => button === document.activeElement), true);
		await page.keyboard.press("ArrowDown"); await page.keyboard.press("Enter");
		await page.getByRole("status").filter({ hasText: "已复制提示词" }).waitFor();
		assert.equal(await page.evaluate(() => navigator.clipboard.readText()), "午后窗边的一束花，温暖的胶片质感");
		await page.keyboard.press("Escape");
		assert.equal(await more.evaluate((button) => button === document.activeElement), true);
		await more.click(); await page.getByRole("menuitem", { name: "另存为", exact: true }).click();
		await more.click(); await page.getByRole("menuitem", { name: "打开所在文件夹", exact: true }).click();
		await page.screenshot({ path: `dist/image-generation/${theme}-gallery.png`, animations: "disabled" });
		await page.locator(".generation-card-preview").click();
		const preview = page.getByRole("dialog", { name: "图片预览", exact: true });
		assert.match(await preview.innerText(), /42 tokens/);
		await page.keyboard.press("Escape");
		await page.evaluate(() => window.skiffPreview.generation.setMode("failure"));
		await prompt().fill("失败用例"); await generate().click();
		await page.getByRole("group", { name: "画廊视图", exact: true }).getByRole("button", { name: /^失败记录/ }).click();
		await page.getByText("生成失败", { exact: true }).waitFor();
		assert.match(await page.locator(".generation-task-list").innerText(), /429/);
		assert.equal(await page.evaluate(() => window.skiffPreview.generation.calls.filter((call) => call.prompt === "失败用例").length), 1);
		await page.locator('.generation-task[data-status="failed"]').getByRole("button", { name: "使用提示词", exact: true }).click();
		assert.equal(await prompt().inputValue(), "失败用例");
		await page.evaluate(() => { const url = new URL(location.href); url.searchParams.set("persist", "1"); history.replaceState(null, "", url); });
		await page.reload();
		await page.getByText("生成作品", { exact: true }).waitFor();
		await page.waitForFunction(() => document.querySelector(".generation-card img")?.naturalWidth > 0);
		assert.equal(await page.locator(".generation-card").count(), 1);
		await page.setViewportSize({ width: 600, height: 800 });
		assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
		await page.getByRole("dialog", { name: "项目与聊天导航" }).waitFor();
		await page.screenshot({ path: `dist/image-generation/${theme}-narrow.png`, animations: "disabled" });
		await page.setViewportSize({ width: 1440, height: 960 });
		await page.evaluate(() => { localStorage.removeItem("skiff.test.images.config"); localStorage.removeItem("skiff.test.images.jobs"); });
		console.log(`PASS ${theme}: service/key configuration, sizes, task switching/cancellation, generation, actions, errors, persistence and narrow layout`);
	}
	assert.deepEqual(errors, []);
} finally { await browser.close(); }
